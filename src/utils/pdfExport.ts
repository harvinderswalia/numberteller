    if (highlight) { this.fill(C.navy3); this.doc.roundedRect(this.M, this.y - 1, this.CW, 9, 1, 1, 'F'); }
    this.tc(highlight ? C.teal : C.dgray);
    this.doc.setFont('helvetica', 'normal');
    this.doc.setFontSize(7.5);
    this.doc.text(stage, this.M + 4, this.y + 4.5);
    this.tc(highlight ? C.white : C.lgray);
    this.doc.setFont('helvetica', 'bold');
    this.doc.setFontSize(8.5);
    this.doc.text(String(value), this.M + 65, this.y + 4.5);
    this.tc(C.dgray);
    this.doc.setFont('helvetica', 'normal');
    this.doc.setFontSize(7);
    this.doc.text(ageRange, this.W - this.M - 4, this.y + 4.5, { align: 'right' });
