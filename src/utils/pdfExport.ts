  // Body paragraph ─────────────────────────────────────────────────────────────
  body(txt: string, color = C.lgray) {
    this.tc(color);
    this.doc.setFont('helvetica', 'normal');
    this.doc.setFontSize(8.5);
    const lines = this.doc.splitTextToSize(txt, this.CW);
    lines.forEach((line: string) => {
      this.need(6);
      this.doc.text(line, this.M, this.y);
      this.y += 5;
    });
  }

  // Bullet item ────────────────────────────────────────────────────────────────
  bullet(txt: string, dotColor = C.teal) {
    this.need(6);
    this.fill(dotColor);
    this.doc.circle(this.M + 3, this.y - 1, 1, 'F');
    this.tc(C.lgray);
    this.doc.setFont('helvetica', 'normal');
    this.doc.setFontSize(8.5);
    const lines = this.doc.splitTextToSize(txt, this.CW - 9);
    this.doc.text(lines, this.M + 7, this.y);
    this.y += lines.length * 5 + 0.5;
  }

