      this.fill(C.navy2);
      this.doc.rect(cx, gridTop, cellW - 1.5, cellH, 'F');
      // Accent bar at top of cell
      this.fill(i === 0 ? C.teal : i === 1 ? C.gold : i === 2 ? C.emerald : C.dgray);
