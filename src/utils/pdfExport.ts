      const traitsText = interp.traits.slice(0, 3).join('  ·  ');
      const traitLines = this.doc.splitTextToSize(traitsText, maxW);
      this.doc.text(traitLines.slice(0, 2), textX, this.y + 19);

      // Challenges
      this.tc(C.gold2);
